#!/usr/bin/env python3
"""Generate bash/zsh/fish completions in completions/ from `polytabletop list` ids.

Usage: python3 -I tools/gen_completions.py [path/to/polytabletop]
Default binary: target/release/polytabletop, else `polytabletop` from PATH.
"""
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
binary = sys.argv[1] if len(sys.argv) > 1 else None
if binary is None:
    cand = os.path.join(ROOT, "target", "release", "polytabletop")
    binary = cand if os.path.exists(cand) else shutil.which("polytabletop")
if not binary:
    sys.exit("polytabletop binary not found; build it or pass its path")

out = subprocess.run([binary, "list"], capture_output=True, text=True, check=True).stdout
ids = []
for line in out.splitlines():
    m = re.match(r"^([a-z0-9_-]+)\s+\S", line)  # id line; rule lines start with spaces
    if m:
        ids.append(m.group(1))
if not ids:
    sys.exit("no game ids parsed from `polytabletop list`")
words = " ".join(ids)
kinds = "implemented traditional branded toolkit"
you = "one two both none"
d = os.path.join(ROOT, "completions")
os.makedirs(d, exist_ok=True)

bash = f"""# bash completion for polytabletop (generated by tools/gen_completions.py)
_polytabletop() {{
    local cur prev
    cur="${{COMP_WORDS[COMP_CWORD]}}"; prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    case "$prev" in
        play) COMPREPLY=($(compgen -W "{words}" -- "$cur")); return;;
        --you) COMPREPLY=($(compgen -W "{you}" -- "$cur")); return;;
        --kind) COMPREPLY=($(compgen -W "{kinds}" -- "$cur")); return;;
    esac
    if [ "$COMP_CWORD" -eq 1 ]; then
        COMPREPLY=($(compgen -W "list catalog play" -- "$cur"))
    else
        COMPREPLY=($(compgen -W "--you --seed --kind" -- "$cur"))
    fi
}}
complete -F _polytabletop polytabletop
"""
zsh = f"""#compdef polytabletop
# zsh completion for polytabletop (generated by tools/gen_completions.py)
_polytabletop() {{
  local -a games
  games=({words})
  if (( CURRENT == 2 )); then
    _values 'command' list catalog play
    return
  fi
  case "$words[CURRENT-1]" in
    play) _values 'game' $games ;;
    --you) _values 'you' {you} ;;
    --kind) _values 'kind' {kinds} ;;
    *) _values 'option' --you --seed --kind ;;
  esac
}}
_polytabletop "$@"
"""
fish = f"""# fish completion for polytabletop (generated by tools/gen_completions.py)
complete -c polytabletop -f
complete -c polytabletop -n __fish_use_subcommand -a "list catalog play"
complete -c polytabletop -n "__fish_seen_subcommand_from play" -a "{words}"
complete -c polytabletop -n "__fish_seen_subcommand_from play" -l you -x -a "{you}"
complete -c polytabletop -n "__fish_seen_subcommand_from play" -l seed -x
complete -c polytabletop -n "__fish_seen_subcommand_from catalog" -l kind -x -a "{kinds}"
"""
for name, text in (("polytabletop.bash", bash), ("_polytabletop", zsh), ("polytabletop.fish", fish)):
    with open(os.path.join(d, name), "w", encoding="utf-8") as f:
        f.write(text)
print(f"{len(ids)} game ids -> {d}")

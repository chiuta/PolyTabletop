//! Cele 16 pachete de conținut ale motorului `aventura` (lumi, nume și texte ORIGINALE).
//!
//! Fiecare pachet = un stil de rol (mecanica de test a presetării corespunzătoare), trei arhetipuri,
//! 6–8 monștri/obstacole, 7–8 scene într-un graf mic, un tabel d6 de evenimente și o resursă proprie.
//! Nivelurile (`skills`, `lvl`) sunt abstracte 1..=6; motorul le scalează după mecanică.

use crate::aventura::{Arch, Foe, Mech, Pack, ResMode, Scene, Sp, BOSS, SK, TERROR, TOUGH};

const fn ar(
    name: &'static str,
    hp: i32,
    skills: [u8; 3],
    dmg: i32,
    def: u8,
    sp: Sp,
    sp_name: &'static str,
) -> Arch {
    Arch {
        name,
        hp,
        skills,
        dmg,
        def,
        sp,
        sp_name,
    }
}
const fn fo(name: &'static str, hp: i32, lvl: u8, dmg: i32, def: u8, flags: u8) -> Foe {
    Foe {
        name,
        hp,
        lvl,
        dmg,
        def,
        flags,
    }
}
const fn sc(name: &'static str, text: &'static str, kind: SK, exits: &'static [u8]) -> Scene {
    Scene {
        name,
        text,
        kind,
        exits,
    }
}

pub fn pack_by_id(id: &str) -> Option<&'static Pack> {
    PACKS.iter().find(|p| p.id == id)
}

